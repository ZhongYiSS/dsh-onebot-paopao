import { readdirSync } from 'node:fs';
/** 家里梗图目录：聊天里的表情包优先从这里挑。 */
const MEME_DIR = 'D:\\AI\\蓝色大肥鱼\\图片\\表情包\\memes';
/**
 * 列出梗图文件名（去掉扩展名）。
 * @returns 名字数组，读不到就是空数组。
 */
function memeNames() {
    try {
        return readdirSync(MEME_DIR)
            .filter((name) => /\.(png|jpe?g|gif|webp)$/i.test(name))
            .map((name) => name.replace(/\.[^.]+$/, ''))
            .sort();
    }
    catch {
        return [];
    }
}
